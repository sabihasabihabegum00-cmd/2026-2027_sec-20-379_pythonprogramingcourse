# Create tuples
first = (1, 2, 3)
second = (4, 5)

# Join tuples
print("Concatenation:", first + second)

# Repeat a tuple
print("Repetition:", first * 2)

# Check membership
print("2 is in first:", 2 in first)
print("6 is not in first:", 6 not in first)

# Compare tuples
print("first equals second:", first == second)