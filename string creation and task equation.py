# Create strings
first_name = "Sam"
language = "Python"

# Combine strings
message = first_name + " is learning " + language
print("Combined:", message)

# Repeat a string
print("Repeated:", language * 3)

# Find the length
print("Length:", len(message))

# Access characters
print("First character:", message[0])
print("Last character:", message[-1])

# Get part of a string
print("First three characters:", language[:3])

# Check whether text is present
print("'Python' is in the message:", "Python" in message)