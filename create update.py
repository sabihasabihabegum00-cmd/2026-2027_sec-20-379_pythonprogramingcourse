# Create a dictionary
student = {
    "name": "Asha",
    "age": 16,
    "grade": "10th"
}

# Access values
print("Name:", student["name"])
print("Age:", student["age"])

# Update a value
student["grade"] = "11th"

# Add a new key-value pair
student["subject"] = "Python"

print("Updated dictionary:", student)