# Demonstrate Python logical operators: and, or, not

a = 10
b = 5
c = 0

print("a > b and b > c:", a > b and b > c)  # True if both conditions are true
print("a > b or b < c: ", a > b or b < c)   # True if at least one condition is true
print("not (a > b):    ", not (a > b))      # Reverses the result